-- GAP 4: TIMESTAMP columns hold UTC, so the defaults must be UTC too.
-- Plain now() would store the server's local time (IST, +5h30m).
ALTER TABLE ratings ALTER COLUMN rated_at   SET DEFAULT (now() AT TIME ZONE 'UTC');
ALTER TABLE users   ALTER COLUMN created_at SET DEFAULT (now() AT TIME ZONE 'UTC');

-- GAP 7: auto-number tags.tag_row_id. Skipped if it is already an identity.
DO $$
BEGIN
    IF (SELECT attidentity FROM pg_attribute
         WHERE attrelid = 'tags'::regclass AND attname = 'tag_row_id') = '' THEN
        ALTER TABLE tags ALTER COLUMN tag_row_id ADD GENERATED BY DEFAULT AS IDENTITY;
    END IF;
END
$$;

-- Next generated id = max(tag_row_id) + 1, so it never collides with loaded rows.
SELECT setval(pg_get_serial_sequence('tags', 'tag_row_id'),
              (SELECT coalesce(max(tag_row_id), 0) FROM tags) + 1, false);
