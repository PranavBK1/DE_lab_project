-- =============================================================================
-- sql/migrations/002_movies_identity.sql
--
-- Auto-number movies.movie_id so the Admin page can add a movie without
-- choosing an id. Re-runnable. A fresh full load (etl/load.py) already
-- produces this state (sql/schema.sql + the identity restart after COPY).
-- =============================================================================

DO $$
BEGIN
    IF (SELECT attidentity FROM pg_attribute
         WHERE attrelid = 'movies'::regclass AND attname = 'movie_id') = '' THEN
        ALTER TABLE movies ALTER COLUMN movie_id ADD GENERATED BY DEFAULT AS IDENTITY;
    END IF;
END
$$;

-- Next generated id = max(movie_id) + 1, so it never collides with MovieLens ids.
SELECT setval(pg_get_serial_sequence('movies', 'movie_id'),
              (SELECT coalesce(max(movie_id), 0) FROM movies) + 1, false);
