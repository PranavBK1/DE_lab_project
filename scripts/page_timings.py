"""Cold and warm load time of every dashboard page -> reports/page_timings.md

Usage:  python scripts/page_timings.py

Each page is run through app/Home.py with streamlit.testing.v1.AppTest, as
demo_user1 (Admin as admin):
  cold = st.cache_data cleared first, so every query runs against PostgreSQL
  warm = the same page again, answered from st.cache_data
The time covers running the page script, which is dominated by computing its
data. Browser rendering is not included. Targets: warm < 1 s, cold < 3 s.
"""
import os
import sys
import time
from datetime import datetime, timezone
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "app"))

import streamlit as st                                  # noqa: E402
from streamlit.testing.v1 import AppTest                # noqa: E402

import db                                               # noqa: E402,F401  (loads .env)

REPORT = ROOT / "reports" / "page_timings.md"
USER = {"user_id": 1, "username": "demo_user1", "role": "user"}
ADMIN = {"user_id": 200000, "username": os.environ.get("DEMO_ADMIN_USERNAME", "admin"), "role": "admin"}

# (label, view, user, movie_id). Movie pages are timed with a blockbuster
# (The Matrix, ~84k ratings) and with a small movie.
CASES = [
    ("Overview", "overview", USER, None),
    ("(a) tags: The Matrix", "a_movie_tags", USER, 2571),
    ("(b) top movies (both tabs)", "b_top_movies", USER, None),
    ("(c) tags by genre: all genres", "c_tags_by_genre", USER, None),
    ("(d) distribution: The Matrix", "d_rating_distribution", USER, 2571),
    ("(d) distribution: Toy Story", "d_rating_distribution", USER, 1),
    ("(d) distribution: small movie (Sabrina, 1995)", "d_rating_distribution", USER, 7),
    ("(e) ratings per movie", "e_ratings_per_movie", USER, None),
    ("(f) top genre: 1995", "f_genre_by_year", USER, None),
    ("(g) genre coverage", "g_genre_coverage", USER, None),
    ("My ratings (demo_user1, 70 ratings)", "my_ratings", USER, None),
    ("Admin (all tabs)", "admin", ADMIN, None),
]
WARM_LIMIT, COLD_LIMIT = 1.0, 3.0


def run_page(view, user, movie_id, cold):
    at = AppTest.from_file(str(ROOT / "app" / "Home.py"), default_timeout=120)
    at.session_state["user"] = user
    if movie_id is not None:
        at.session_state["movie_id"] = movie_id
    at.run()
    at.switch_page(f"views/{view}.py")
    if cold:                       # after the first run, which already rendered the default page
        st.cache_data.clear()
    t0 = time.perf_counter()
    at.run()
    seconds = time.perf_counter() - t0
    assert not at.exception, [e.value for e in at.exception]
    return seconds


def main():
    rows = []
    for label, view, user, movie_id in CASES:
        cold = run_page(view, user, movie_id, cold=True)
        warm = run_page(view, user, movie_id, cold=False)
        ok = warm < WARM_LIMIT and cold < COLD_LIMIT
        rows.append((label, cold, warm, ok))
        print(f"{label:<48}{cold:>7.2f} s cold{warm:>7.2f} s warm   {'PASS' if ok else 'FAIL'}")

    now = datetime.now(timezone.utc).strftime("%Y-%m-%d %H:%M UTC")
    out = [
        "# Page timings",
        "",
        f"Generated by `scripts/page_timings.py` on {now}. Each page was run through `app/Home.py` "
        "with Streamlit's AppTest. **Cold** means the app cache was cleared first, so every query "
        "went to PostgreSQL. **Warm** means the same page again, served from `st.cache_data`. "
        "The times cover running the page script, which is dominated by computing its data; "
        f"browser rendering is not included. Target: warm < {WARM_LIMIT:.0f} s, cold < {COLD_LIMIT:.0f} s.",
        "",
        "| page | cold s | warm s | result |",
        "|---|---:|---:|---|",
    ]
    out += [f"| {l} | {c:.2f} | {w:.2f} | {'PASS' if ok else '**FAIL**'} |" for l, c, w, ok in rows]
    out += ["", f"**{sum(r[3] for r in rows)} of {len(rows)} pass.**", ""]
    out += ["## Page (d) and blockbusters", "",
            "Page (d) used to take 6–10 s on a cold cache for blockbusters, because their ratings are spread "
            "over ~53,000 pages of the 1.2 GB `ratings` table. It now reads the stored histogram "
            "`movie_stats.rating_hist` (one row), so blockbusters load as fast as any other movie. "
            "See [query_performance.md](query_performance.md).", ""]
    REPORT.write_text("\n".join(out), encoding="utf-8")
    print(f"wrote {REPORT.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
